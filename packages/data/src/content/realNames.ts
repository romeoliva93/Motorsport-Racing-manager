export function normalizeName(s: string): string {
  return s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[-'\s]+/g, ' ')
    .trim()
    .toLowerCase();
}

const BLOCKED = new Set(REAL_RIDER_SURNAMES.map(normalizeName));

export function isBlockedSurname(lastName: string): boolean {
  return BLOCKED.has(normalizeName(lastName));
}
